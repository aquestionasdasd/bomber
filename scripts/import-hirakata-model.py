"""Package the reviewed, original Hirakata study GLB as a synchronous JS asset.

No Blender, video, audio, network or third-party asset conversion is executed.
The game map factory is synchronous so its destruction snapshots see all meshes.
"""
from pathlib import Path
import argparse
import base64
import hashlib
import json
import struct


def main():
    repo = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=repo.parent / "output/hirakata-complete-model-20261102/hirakata-complete.glb")
    parser.add_argument("--output", type=Path, default=repo / "public/assets/hirakata-complete-model.js")
    args = parser.parse_args()
    raw = args.input.read_bytes()
    if len(raw) < 28 or struct.unpack_from("<III", raw) != (0x46546C67, 2, len(raw)):
        raise ValueError("Invalid GLB v2 header")
    size, kind = struct.unpack_from("<II", raw, 12)
    if kind != 0x4E4F534A or 20 + size + 8 > len(raw):
        raise ValueError("Missing JSON chunk")
    model = json.loads(raw[20:20 + size])
    bin_size, bin_kind = struct.unpack_from("<II", raw, 20 + size)
    if bin_kind != 0x004E4942 or 28 + size + bin_size != len(raw):
        raise ValueError("Expected one complete binary chunk")
    if model.get("textures") or model.get("images"):
        raise ValueError("This original geometry asset must not embed reference imagery")
    provenance = {
        "id": "hirakata-complete-20261102",
        "source": "hirakata-complete.glb",
        "sha256": hashlib.sha256(raw).hexdigest(),
        "bytes": len(raw),
        "method": "Original scripted geometry interpreted from owner-provided walking videos; estimated dimensions, not a survey or scan.",
        "referencesEmbedded": False,
        "externalMeshOrTextureLibrary": False,
        "textGeometry": "Station labels baked from locally installed Meiryo/Yu Gothic; no font files redistributed.",
        "coordinates": "glTF Y-up; game (x,y,z) already equals authoring (x,z,-y).",
    }
    encoded = base64.b64encode(raw).decode("ascii")
    output = (
        "// Generated by scripts/import-hirakata-model.py. Do not edit the binary string.\n"
        "// Original project geometry; reference video/image and font files are not embedded.\n"
        "export const HIRAKATA_MODEL_PROVENANCE = Object.freeze(" + json.dumps(provenance, ensure_ascii=False, separators=(",", ":")) + ");\n"
        "export const HIRAKATA_MODEL_BASE64 = '" + encoded + "';\n"
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(output, encoding="utf-8", newline="\n")
    print(json.dumps({"inputBytes": len(raw), "moduleBytes": len(output.encode("utf-8")), "sha256": provenance["sha256"], "meshes": len(model["meshes"]), "materials": len(model["materials"])}, ensure_ascii=False))


if __name__ == "__main__":
    main()
